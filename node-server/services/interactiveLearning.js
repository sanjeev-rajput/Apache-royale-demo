import { getLearningCatalog } from "./learningCatalog.js";

const sessions = new Map();
const MAX_QUESTIONS = 10;

function normalize(value = "") {
  return String(value)
    .toLowerCase()
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9\s-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function isPracticeRequest(message = "") {
  return /\b(practice|quiz|test me|ask me (?:a )?question|give me (?:a )?(?:practice question|quiz)|start (?:a )?(?:quiz|practice))\b/i.test(message);
}

function extractGrade(message = "") {
  const text = normalize(message);
  if (/\bnursery\b/.test(text)) return "Nursery";
  const match = text.match(/\b(?:class|grade|standard|std)\s*(?:number\s*)?(\d{1,2})\b/) ||
    text.match(/\b(?:i am in|im in|i study in|studying in)\s*(\d{1,2})\b/);
  if (match) {
    const number = Number(match[1]);
    if (number >= 1 && number <= 12) return `Class ${number}`;
  }
  return "";
}

function findTopic(message = "") {
  const text = normalize(message);
  const matches = [];
  for (const item of getLearningCatalog()) {
    for (const value of [item.subtopic, item.topic]) {
      const candidate = normalize(value || "");
      if (candidate && text.includes(candidate)) matches.push({ value, length: candidate.length });
    }
  }
  matches.sort((a, b) => b.length - a.length);
  return matches[0]?.value || "";
}

function parseJson(text) {
  const cleaned = String(text || "").trim()
    .replace(/^```(?:json)?\s*/i, "")
    .replace(/\s*```$/, "");
  return JSON.parse(cleaned);
}

async function askOllama({ model, url, messages, temperature = 0.3, maxTokens = 350 }) {
  const response = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      model,
      stream: false,
      format: "json",
      options: { temperature, num_predict: maxTokens },
      messages
    }),
    signal: AbortSignal.timeout(60000)
  });
  if (!response.ok) throw new Error(`Ollama practice request failed: ${response.status}`);
  const data = await response.json();
  const content = data.message?.content;
  if (typeof content !== "string" || !content.trim()) {
    throw new Error("Ollama returned an empty practice response");
  }
  return parseJson(content);
}

function validateDeterministicAnswer(question, options, answer, explanation, topic) {
  // Alphabet-sequence questions have a deterministic answer, so do not trust
  // an answer key generated by the language model for these questions.
  const isAlphabetTopic = /\b(alphabet|alphabets|letters)\b/i.test(topic || "");
  const match = String(question || "").match(/\b(?:letter\s+)?(?:comes\s+)?(after|before)\s+([A-Z])\b/i);
  if (!isAlphabetTopic || !match) return { options, answer, explanation };

  const direction = match[1].toLowerCase();
  const letterCode = match[2].toUpperCase().charCodeAt(0);
  const targetCode = letterCode + (direction === "after" ? 1 : -1);
  if (targetCode < 65 || targetCode > 90) return { options, answer, explanation };

  const correctAnswer = String.fromCharCode(targetCode);
  const correctedOptions = [...options];
  const correctIndex = correctedOptions.findIndex(option => normalize(option) === normalize(correctAnswer));
  if (correctIndex === -1) {
    // Replace the last choice so the correct answer is always available.
    correctedOptions[correctedOptions.length - 1] = correctAnswer;
  }

  return {
    options: correctedOptions,
    answer: correctAnswer,
    explanation: `The letter ${correctAnswer} comes ${direction} ${match[2].toUpperCase()} in the English alphabet.`
  };
}

async function generateQuestion(session, config) {
  const result = await askOllama({
    ...config,
    temperature: 0.5,
    maxTokens: 400,
    messages: [
      {
        role: "system",
        content: `Create exactly one multiple-choice practice question for a school student. Return JSON only with keys question, options, answer, explanation. options must be an array of exactly 3 short choices with only one correct answer. answer must exactly match the correct option. Ensure the answer and explanation are factually correct. Avoid ambiguous questions, multiple valid answers, and questions whose answer is included in the wording. Use simple, age-appropriate language and avoid concepts beyond the student's class. Topic: ${session.topic}. Class: ${session.grade}. Question number: ${session.asked + 1} of ${MAX_QUESTIONS}.`
      },
      ...(session.previousQuestions.length
        ? [{ role: "user", content: `Do not repeat these earlier questions: ${JSON.stringify(session.previousQuestions)}` }]
        : [])
    ]
  });

  const question = String(result.question || "").trim();
  const options = Array.isArray(result.options)
    ? result.options.map(value => String(value).trim()).filter(Boolean).slice(0, 3)
    : [];
  let answer = String(result.answer || "").trim();
  let explanation = String(result.explanation || "").trim();
  if (!question || options.length !== 3 || !answer || !options.some(option => normalize(option) === normalize(answer))) {
    throw new Error("Ollama returned an invalid practice question");
  }

  const validated = validateDeterministicAnswer(question, options, answer, explanation, session.topic);
  answer = validated.answer;
  const finalOptions = validated.options;
  explanation = validated.explanation;

  session.currentQuestion = { question, options: finalOptions, answer, explanation };
  session.asked += 1;
  session.previousQuestions.push(question);

  return `**Question ${session.asked} — ${session.topic} (${session.grade})**\n\n${question}\n\n${finalOptions.map((option, index) => `${String.fromCharCode(65 + index)}. ${option}`).join("\n")}\n\nReply with A, B, C, or your answer.`;
}

function yesOrNo(message) {
  const text = normalize(message);
  if (/^(yes|yes please|yeah|yep|sure|ok|okay|continue|next|next question|lets go|let us go)$/.test(text)) return "yes";
  if (/^(no|no thanks|no thank you|nope|stop|finish|finish quiz|end quiz|quit)$/.test(text)) return "no";
  return "";
}

function finalScore(session, completedAll = false) {
  const total = session.answered;
  const percentage = total ? Math.round((session.score / total) * 100) : 0;
  const opening = completedAll
    ? "🎉 **Quiz completed!**\n\nGreat work! You've completed all 10 questions."
    : "🎉 **Quiz finished!**\n\nGreat work practicing today!";
  return `${opening}\n\n**Your final score: ${session.score}/${total} (${percentage}%)**\n\nWhat would you like to do next?\n\n- Practice this topic again\n- Learn another topic\n- Explore learning activities`;
}

async function evaluateAnswer(session, message, config) {
  const current = session.currentQuestion;
  const cleaned = String(message || "").trim();
  const optionMatch = cleaned.match(/^\s*([abc])\s*[.)]?\s*$/i);
  const selected = optionMatch
    ? current.options[optionMatch[1].toLowerCase().charCodeAt(0) - 97]
    : cleaned;

  let correct = normalize(selected) === normalize(current.answer);
  let feedback = correct ? "Well done! That's correct! 🎉" : "Not quite! That's okay—let's learn together.";

  // Ask Ollama to recognize equivalent wording for free-text answers.
  if (!optionMatch && !correct) {
    try {
      const result = await askOllama({
        ...config,
        temperature: 0,
        maxTokens: 180,
        messages: [
          {
            role: "system",
            content: 'Evaluate whether a student answer means the same as the expected answer. Return JSON only with keys "correct" (boolean) and "feedback" (short, kind, age-appropriate explanation). Do not mark a clearly different answer correct.'
          },
          {
            role: "user",
            content: JSON.stringify({
              grade: session.grade,
              topic: session.topic,
              question: current.question,
              expectedAnswer: current.answer,
              studentAnswer: selected
            })
          }
        ]
      });
      if (typeof result.correct === "boolean") correct = result.correct;
      if (typeof result.feedback === "string" && result.feedback.trim()) feedback = result.feedback.trim();
    } catch (error) {
      console.error("Ollama answer evaluation failed:", error.message);
    }
  }

  if (correct) {
    feedback = "✅ **Correct!** " + (current.explanation || feedback);
    session.score += 1;
  } else {
    feedback = `💡 **Not quite!** The correct answer is **${current.answer}**.\n\n${current.explanation || feedback}`;
  }

  session.answered += 1;
  session.currentQuestion = null;
  session.awaitingContinue = session.answered < MAX_QUESTIONS;

  const scoreLine = `\n\n**Your score: ${session.score}/${session.answered}**`;
  if (session.answered >= MAX_QUESTIONS) {
    sessions.delete(session.id);
    return `${feedback}\n\n${finalScore(session, true)}`;
  }

  return `${feedback}${scoreLine}\n\nWould you like to try the next question?\n\n**Type Yes to continue or No to finish the quiz.**`;
}

// Let an explicit request to change learning modes leave practice mode.
// Without this check, a message such as "Explain nouns" can be mistaken for
// an answer to the practice setup question "Which class are you in?".
function isModeSwitchRequest(message = "") {
  const text = normalize(message);
  return /\b(explain|what is|what are|define|definition|meaning|describe|tell me about|teach me about|i want to learn|i would like to learn|learn about|help me with|show me activities|activities about|explore)\b/.test(text);
}

export async function handlePracticeMessage({
  conversationId,
  message,
  context = {},
  model = "qwen2.5:3b-instruct",
  url = "http://localhost:11434/api/chat"
}) {
  const id = String(conversationId || "").trim();
  if (!id) return null;

  const text = normalize(message);
  const existing = sessions.get(id);
  const config = { model, url };

  if (/\b(stop quiz|end quiz|stop practice|end practice|quit quiz|cancel quiz)\b/.test(text)) {
    if (!existing) return null;
    sessions.delete(id);
    return { handled: true, reply: finalScore(existing), intent: "practice_end" };
  }

  // Explicit explanation/learning requests take priority over pending practice
  // setup, quiz continuation, or answer evaluation. Clear practice state and
  // let the normal chat route handle the new request.
  if (existing && isModeSwitchRequest(message)) {
    sessions.delete(id);
    return null;
  }

  if (existing?.awaitingContinue) {
    const choice = yesOrNo(message);
    if (choice === "no") {
      sessions.delete(id);
      return { handled: true, reply: finalScore(existing), intent: "practice_end" };
    }
    if (choice === "yes") {
      if (existing.answered >= MAX_QUESTIONS) {
        sessions.delete(id);
        return { handled: true, reply: finalScore(existing, true), intent: "practice_end" };
      }
      existing.awaitingContinue = false;
      return { handled: true, reply: await generateQuestion(existing, config), intent: "practice_question" };
    }
    return {
      handled: true,
      reply: "Would you like to try the next question?\n\n**Type Yes to continue or No to finish the quiz.**",
      intent: "practice_continue_prompt"
    };
  }

  if (!isPracticeRequest(message) && !existing) return null;

  if (isPracticeRequest(message) && !existing) {
    const topic = findTopic(message) || context.subtopic || context.topic || "";
    const grade = extractGrade(message) || context.grade || "";
    const session = {
      id,
      topic,
      grade,
      score: 0,
      asked: 0,
      answered: 0,
      currentQuestion: null,
      previousQuestions: [],
      awaitingContinue: false,
      waitingFor: ""
    };
    sessions.set(id, session);

    if (!session.topic) {
      session.waitingFor = "topic";
      return { handled: true, reply: "What topic would you like to practice? For example, nouns, verbs, or fractions.", intent: "practice_setup" };
    }
    if (!session.grade) {
      session.waitingFor = "grade";
      return { handled: true, reply: `Great! We'll practice **${session.topic}**. Which class are you in?`, intent: "practice_setup" };
    }
    return { handled: true, reply: await generateQuestion(session, config), intent: "practice_question" };
  }

  if (existing?.waitingFor === "topic") {
    existing.topic = findTopic(message) || String(message).trim();
    existing.waitingFor = "grade";
    return { handled: true, reply: `Okay, let's practice **${existing.topic}**. Which class are you in?`, intent: "practice_setup" };
  }

  if (existing?.waitingFor === "grade") {
    const grade = extractGrade(message);
    if (!grade) {
      return { handled: true, reply: "Please tell me your class, for example, Class 1 or Class 5.", intent: "practice_setup" };
    }
    existing.grade = grade;
    existing.waitingFor = "";
    return { handled: true, reply: await generateQuestion(existing, config), intent: "practice_question" };
  }

  if (existing?.currentQuestion) {
    return { handled: true, reply: await evaluateAnswer(existing, message, config), intent: "practice_feedback" };
  }

  return null;
}
