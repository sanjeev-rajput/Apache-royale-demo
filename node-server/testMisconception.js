import { analyzeMisconception } from "./services/misconceptionDetector.js";
import { createOllamaJsonGenerator } from "./services/ollamaJsonAdapter.js";

const generateStructuredResponse = createOllamaJsonGenerator({
  model: process.env.OLLAMA_MODEL || "qwen3.5:4b",
  url: process.env.OLLAMA_URL || "http://localhost:11434/api/chat",
  temperature: 0,
  maxTokens: 500
});

const initialCases = [
  {
    name: "Scenario 1 — Explicit fraction reasoning",
    input: {
      grade: "Class 5",
      topic: "Fractions",
      question: "Which is larger, 1/2 or 1/4? Explain your thinking.",
      expectedAnswer: "1/2 is larger because one half is greater than one quarter.",
      studentAnswer: "1/4 is larger because 4 is bigger than 2."
    }
  },
  {
    name: "Scenario 2 — Incorrect arithmetic answer without reasoning",
    input: {
      grade: "Class 4",
      topic: "Multiplication",
      question: "What is 7 multiplied by 8?",
      expectedAnswer: "56",
      studentAnswer: "54"
    }
  },
  {
    name: "Scenario 3 — Insufficient explanation",
    input: {
      grade: "Class 5",
      topic: "Fractions",
      question: "Why is 1/2 larger than 1/3?",
      expectedAnswer: "When the same whole is divided into fewer equal parts, each part is larger.",
      studentAnswer: "Because it is."
    }
  }
];

async function runInitialCase(testCase) {
  console.log("\n==================================================");
  console.log(testCase.name);
  console.log("==================================================");

  const result = await analyzeMisconception({
    ...testCase.input,
    mode: "normalChat",
    generateStructuredResponse,
    conversationHistory: [],
    followUpCount: 0
  });

  console.log(JSON.stringify(result, null, 2));
  return { input: testCase.input, result };
}

async function runFollowUpBranch({
  title,
  initialTurn,
  followUpAnswer
}) {
  const { input, result } = initialTurn;

  if (!result.followUpQuestion) {
    console.log(`\n${title}: skipped because the initial AI assessment generated no follow-up.`);
    return;
  }

  console.log("\n==================================================");
  console.log(title);
  console.log("==================================================");
  console.log("Diagnostic question:", result.followUpQuestion);
  console.log("Student response:", followUpAnswer);

  const history = [{
    question: input.question,
    studentAnswer: input.studentAnswer,
    followUpQuestion: result.followUpQuestion,
    followUpAnswer
  }];

  const nextResult = await analyzeMisconception({
    ...input,
    studentAnswer: followUpAnswer,
    mode: "normalChat",
    generateStructuredResponse,
    conversationHistory: history,
    followUpCount: result.nextFollowUpCount ?? 1
  });

  console.log(JSON.stringify(nextResult, null, 2));
  return nextResult;
}

async function main() {
  console.log("Provider-independent, two-pass misconception service test");
  console.log("Provider adapter: Ollama");
  console.log("Model:", process.env.OLLAMA_MODEL || "qwen3.5:4b");

  const completed = [];

  for (const testCase of initialCases) {
    try {
      completed.push(await runInitialCase(testCase));
    } catch (error) {
      console.error("Test failed:", error.message);
    }
  }

  const multiTurnSeed = completed.find(
    item => item.input.topic === "Fractions" &&
      item.input.studentAnswer === "Because it is."
  );

  if (multiTurnSeed) {
    // These are test inputs, not application-side classification rules.
    // Both branches use the actual follow-up generated by the model.
    const branches = [
      {
        title: "Scenario 4 — Follow-up demonstrates understanding",
        followUpAnswer:
          "The two slices are bigger because the same whole is divided into fewer equal pieces. Each piece gets more of the whole."
      },
      {
        title: "Scenario 5 — Follow-up reveals a misconception",
        followUpAnswer:
          "The three slices are bigger because three is more than two."
      }
    ];

    for (const branch of branches) {
      try {
        await runFollowUpBranch({
          ...branch,
          initialTurn: multiTurnSeed
        });
      } catch (error) {
        console.error(`${branch.title} failed:`, error.message);
      }
    }
  }

  console.log("\nAll test scenarios have finished.");
}

main();
